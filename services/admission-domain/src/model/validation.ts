export type RuleCode = (typeof RULE_CODES)[keyof typeof RULE_CODES];
export type ValidationSeverity = 'INFO' | 'WARNING' | 'REVIEW' | 'ERROR';
export type RuleAuthority =
  'SOURCE_CONFIRMED' | 'AUTHORITY_CONFIGURED' | 'PROPOSED' | 'UNKNOWN_BLOCKING';

export interface ValidationFinding {
  readonly code: RuleCode;
  readonly severity: ValidationSeverity;
  readonly authority: RuleAuthority;
  readonly message: string;
}

export type AdmissionPolicyOutcome = 'ACCEPT' | 'MANUAL_REVIEW' | 'REJECT';

export interface AdmissionPolicyDecision {
  readonly outcome: AdmissionPolicyOutcome;
  readonly targetLifecycleStatus: AdmissionLifecycleStatus;
  readonly evaluatedAt: IsoDateTime;
  readonly rulesetVersion: string;
  readonly approvalSnapshotId: ApprovalSnapshotId | null;
  readonly reservation: CapacityReservation | null;
  readonly findings: readonly ValidationFinding[];
}
